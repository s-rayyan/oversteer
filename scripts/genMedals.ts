// Medal base times: how long the starter Hatchback's benchmark bot takes to drive each whole race, plus a little for
// the run-up to the line. src/game/medals.ts turns these into bronze, silver and gold times.
//   npm run medals            check that src/game/medalTimes.ts is up to date
//   npm run medals -- --write regenerate it (run after `npm run benchmark -- --write`)
import { readFileSync, writeFileSync } from 'node:fs';
import { TRACKS } from '../src/game/tracks.ts';

const WRITE = process.argv.includes('--write');
const RUN_UP = 1.5; // seconds: the car starts a little behind the line
const laps = JSON.parse(readFileSync(new URL('./benchmarkLaps.json', import.meta.url), 'utf8')) as Record<string, Record<string, number>>;

const rows = TRACKS.map((t) => {
  const lap = laps[t.id]?.hatch;
  if (lap === undefined) throw new Error(`no benchmark lap for ${t.id}: run npm run benchmark -- --write`);
  return `  '${t.id}': ${(lap * t.laps + RUN_UP).toFixed(1)},`;
});
const file = `// GENERATED by \`npm run medals -- --write\`. Do not edit by hand.
// Seconds for the starter Hatchback's benchmark bot to drive each whole race (see scripts/genMedals.ts).
export const MEDAL_BASE: Record<string, number> = {
${rows.join('\n')}
};
`;
const path = new URL('../src/game/medalTimes.ts', import.meta.url);
if (WRITE) {
  writeFileSync(path, file);
  console.log(`wrote ${TRACKS.length} tracks to src/game/medalTimes.ts`);
} else {
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
  if (current !== file) { console.log('FAIL: src/game/medalTimes.ts is out of date. Run: npm run medals -- --write'); process.exit(1); }
  console.log('ok   src/game/medalTimes.ts is up to date');
}
