// Laps every track with every car using the headless simulator (same physics as the game) and checks
// that every car class wins somewhere.
//   npm run benchmark            print the results and verify src/game/trackBest.ts is up to date
//   npm run benchmark -- --write regenerate scripts/benchmarkLaps.json and src/game/trackBest.ts
// Cars are driven by a simple line-following bot, so this measures clean-racing pace, not skilled play.
import { readFileSync, writeFileSync } from 'node:fs';
import { CARS, CAR_CLASSES, type CarClassId } from '../src/game/cars.ts';
import { TRACKS } from '../src/game/tracks.ts';
import { baselineBot, carStats, lapTime, roadFor } from './sim.ts';

const WRITE = process.argv.includes('--write');
const ORDER = Object.keys(CAR_CLASSES) as CarClassId[];
const ROLE = ORDER.filter((c) => c !== 'hypercar'); // the seven cars you can buy without saving for a hypercar

const laps: Record<string, Record<string, number>> = {};
const best: Record<string, { best: CarClassId; bestRole: CarClassId; margin: number }> = {};
const wins: Record<string, string[]> = Object.fromEntries(ORDER.map((c) => [c, [] as string[]]));
const margins: Record<string, number[]> = Object.fromEntries(ORDER.map((c) => [c, [] as number[]]));

for (const t of TRACKS) {
  const road = roadFor(t);
  laps[t.id] = {};
  for (const c of CARS) laps[t.id][c.id] = +(lapTime(road, carStats(c), baselineBot).lap ?? 999).toFixed(2);
  const mean = (cls: CarClassId) => { const l = CARS.filter((c) => c.carClass === cls).map((c) => laps[t.id][c.id]); return l.reduce((a, b) => a + b, 0) / l.length; };
  const rank = [...ORDER].sort((a, b) => mean(a) - mean(b)); // every class against every other class
  const margin = ((mean(rank[1]) - mean(rank[0])) / mean(rank[0])) * 100;
  const bestRole = [...ROLE].sort((a, b) => mean(a) - mean(b))[0];
  best[t.id] = { best: rank[0], bestRole, margin: +margin.toFixed(1) };
  wins[rank[0]].push(t.name);
  margins[rank[0]].push(margin);
}

console.log('class        wins  (fastest of ALL eight classes, by mean lap)   smallest win margin');
for (const c of ORDER) console.log(`${CAR_CLASSES[c].label.padEnd(12)} ${String(wins[c].length).padStart(3)}   ${(wins[c].slice(0, 5).join(', ') + (wins[c].length > 5 ? ', ...' : '')).padEnd(60)} ${margins[c].length ? Math.min(...margins[c]).toFixed(1) + '%' : '-'}`);
const roleOnly = TRACKS.filter((t) => best[t.id].bestRole !== best[t.id].best).length;
console.log(`\ntracks where the fastest class is out of reach of a hypercar-free garage: ${roleOnly} (best affordable class differs)`);

const empty = ORDER.filter((c) => wins[c].length === 0);
const lines = TRACKS.map((t) => `  '${t.id}': { best: '${best[t.id].best}', bestRole: '${best[t.id].bestRole}', margin: ${best[t.id].margin} },`);
const file = `// GENERATED by \`npm run benchmark -- --write\`. Do not edit by hand.
// For each track: the car class with the fastest mean lap in the headless benchmark, the fastest class
// among the seven you can buy without a Hypercar, and the winner's margin over the runner-up (%).
import type { CarClassId } from './cars';

export interface TrackBest {
  best: CarClassId;
  bestRole: CarClassId;
  margin: number;
}

export const TRACK_BEST: Record<string, TrackBest> = {
${lines.join('\n')}
};
`;
if (WRITE) {
  writeFileSync(new URL('./benchmarkLaps.json', import.meta.url), JSON.stringify(laps));
  writeFileSync(new URL('../src/game/trackBest.ts', import.meta.url), file);
  console.log('\nwrote scripts/benchmarkLaps.json and src/game/trackBest.ts');
} else {
  let current = '';
  try { current = readFileSync(new URL('../src/game/trackBest.ts', import.meta.url), 'utf8'); } catch { /* not generated yet */ }
  if (current !== file) { console.log('\nFAIL: src/game/trackBest.ts is out of date. Run: npm run benchmark -- --write'); process.exit(1); }
  console.log('\nsrc/game/trackBest.ts is up to date');
}
if (empty.length) { console.log(`FAIL: no wins for ${empty.join(', ')}`); process.exit(1); }
console.log('every one of the eight car classes wins at least one track');
